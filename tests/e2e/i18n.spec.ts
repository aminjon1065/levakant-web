import { expect, test, type Page } from '@playwright/test';

const CYR = /[А-Яа-яЁё]/;
const RU_ONLY = /[цщыьЦЩЫЬ]/; // Russian letters that Tajik does not use
// Proper names that stay as they are in every language.
const KEEP = [/акаи Муъмин/g];

/** Every visible text node and text attribute of the page root. */
async function texts(page: Page) {
  return page.evaluate(() => {
    const root = document.getElementById('lr-root')!;
    const out: string[] = [];
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let n: Node | null;
    while ((n = w.nextNode())) {
      const v = n.nodeValue!.replace(/\s+/g, ' ').trim();
      if (v) out.push(v);
    }
    root.querySelectorAll('[aria-label],[alt],[placeholder],[title]').forEach((el) =>
      ['aria-label', 'alt', 'placeholder', 'title'].forEach((a) => {
        const v = el.getAttribute(a);
        if (v?.trim()) out.push(`@${a}: ${v}`);
      }),
    );
    // text generated by CSS (e.g. "· sun now" on lit façades)
    root.querySelectorAll('*').forEach((el) =>
      (['::before', '::after'] as const).forEach((pe) => {
        const c = getComputedStyle(el, pe).content;
        if (c && c !== 'none' && c !== 'normal' && /[^"' ]/.test(c.replace(/^["']|["']$/g, '')))
          out.push(`@${pe}: ${c}`);
      }),
    );
    out.push(`@title: ${document.title}`);
    return out;
  });
}

/** Walk through states whose strings only appear after interaction. */
async function visitStates(page: Page, collect: () => Promise<void>) {
  await collect();
  // text of every section (content-visibility skips unrendered ones in getComputedStyle)
  await page.evaluate(() =>
    document.querySelectorAll('section').forEach((s) => (s.style.contentVisibility = 'visible')),
  );
  await collect();
  const b = page.locator('#building');
  await b.locator('.fr button').nth(1).click(); // 9th floor
  await b.locator('.b3-ct .b3-ex').click(); // explode
  await b.locator('.b3-i .chips button').first().click();
  await collect();
  await b.locator('.fr button').last().click(); // lower level
  await collect();
  await page
    .locator('#commerce .c-tg button, #commerce [aria-pressed]')
    .last()
    .click()
    .catch(() => {});
  await collect();
  await page.locator('#apartments .cv-md button').nth(1).click(); // 3D apartment
  await page.locator('#apartments .rt button:not([disabled])').first().click();
  await collect();
  await page.locator('#apartments .cl .lc').last().click(); // 4-room attic
  await page.locator('#apartments .cv-f .chip').click(); // favourite
  await collect();
  await page.locator('#apartments .cv-md button').first().click();
  await page.locator('#apartments .cv-tl .tb').last().click(); // full screen plan
  await collect();
  await page.keyboard.press('Escape');
  await page.locator('#gallery .gi').first().click();
  await collect();
  await page.keyboard.press('Escape');
  await page.locator('#contact .fm-f button').click(); // errors
  await expect(page.locator('#f-name')).toBeFocused(); // the form moves focus to the first invalid field
  await collect();
  await page.locator('#f-name').fill('Test');
  await page.locator('#f-tel').fill('+992 90 000 00 00');
  await page.locator('#contact .fm-f button').click();
  await expect(page.locator('#contact [role=status]')).toBeVisible({ timeout: 10_000 });
  await collect();
}

for (const [locale, bad] of [
  ['en', CYR],
  ['tg', RU_ONLY],
] as const) {
  test(`no Russian left on /${locale} @all`, async ({ page }) => {
    // mocked enquiry endpoint, to reach the "enquiry received" state
    await page.route('**/api/leads', (route) =>
      route.fulfill({ json: route.request().method() === 'GET' ? { enabled: true } : { ok: true } }),
    );
    await page.goto(`/${locale}`);
    await page.waitForLoadState('networkidle');
    const found = new Set<string>();
    await visitStates(page, async () => {
      for (const t of await texts(page)) {
        const s = KEEP.reduce((x, re) => x.replace(re, ''), t);
        if (bad.test(s)) found.add(t);
      }
    });
    expect([...found]).toEqual([]);
  });
}
